import Foundation

/// Shell scripts embedded in the generated packages.
///
/// Templates use Swift raw strings (`#"""`) so shell syntax such as `$(...)` and `\"`
/// is written verbatim; only `\#(...)` is interpolated by Swift.
nonisolated enum ScriptTemplates {
    /// Temporary location the PKG installs its payload to. The postinstall script copies it
    /// into each user's Teams folder and then deletes it, so nothing is left behind outside
    /// the Teams folders (and macOS clears `/private/tmp` on restart as a fallback).
    static func pkgPayloadPath(for options: BuildOptions) -> String {
        "/private/tmp/TeamsBackgrounds/\(options.safeName)"
    }

    /// Script that copies the backgrounds into the Teams upload folder(s) and restarts Teams.
    ///
    /// Run as a normal user it installs for that user only. Run as root (PKG postinstall,
    /// MDM, Intune) it installs for the console user or every local user.
    static func installScript(options: BuildOptions, imageCount: Int) -> String {
        let timestamp = ISO8601DateFormatter().string(from: .now)
        return #"""
        #!/bin/bash
        #
        # Installs custom Microsoft Teams backgrounds.
        # Package: \#(shellEscaped(options.packageName))
        # Generated by Teams Backgrounds on \#(timestamp) (\#(imageCount) image(s)).
        #
        # Usage: install-backgrounds.sh [source-folder]
        #   - Run as a normal user to install for yourself.
        #   - Run as root (PKG / MDM / Intune) to install for local users.

        PACKAGE_NAME=\#(shellEscaped(options.packageName))
        INSTALL_NEW_TEAMS=\#(options.teamsTarget.includesNew ? 1 : 0)
        INSTALL_CLASSIC_TEAMS=\#(options.teamsTarget.includesClassic ? 1 : 0)
        RESTART_TEAMS=\#(options.restartTeams ? 1 : 0)
        ALL_USERS=\#(options.installForAllUsers ? 1 : 0)

        SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
        SOURCE_DIR="${1:-$SCRIPT_DIR/Backgrounds}"

        NEW_TEAMS_BUNDLE_ID="com.microsoft.teams2"
        CLASSIC_TEAMS_BUNDLE_ID="com.microsoft.teams"
        NEW_TEAMS_UPLOADS="Library/Containers/com.microsoft.teams2/Data/Library/Application Support/Microsoft/MSTeams/Backgrounds/Uploads"
        CLASSIC_TEAMS_UPLOADS="Library/Application Support/Microsoft/Teams/Backgrounds/Uploads"

        log() {
            echo "$(date '+%Y-%m-%d %H:%M:%S') [$PACKAGE_NAME] $*"
        }

        is_root() {
            [ "$(id -u)" -eq 0 ]
        }

        if [ ! -d "$SOURCE_DIR" ]; then
            log "Source folder not found: $SOURCE_DIR"
            exit 1
        fi

        shopt -s nullglob
        IMAGES=("$SOURCE_DIR"/*.png)
        if [ ${#IMAGES[@]} -eq 0 ]; then
            log "No images found in $SOURCE_DIR"
            exit 1
        fi

        # Runs a command as the given user, so created folders and files are owned by them.
        run_as() {
            local user="$1"
            shift
            if is_root; then
                sudo -u "$user" "$@"
            else
                "$@"
            fi
        }

        home_for_user() {
            dscl . -read "/Users/$1" NFSHomeDirectory 2>/dev/null | sed 's/^NFSHomeDirectory: //'
        }

        copy_backgrounds() {
            local user="$1" home="$2" relative="$3"
            local dest="$home/$relative"

            if ! run_as "$user" mkdir -p "$dest"; then
                log "Could not create $dest"
                return 1
            fi

            local copied=0
            for image in "${IMAGES[@]}"; do
                if run_as "$user" cp -f "$image" "$dest/"; then
                    copied=$((copied + 1))
                else
                    log "Failed to copy $(basename "$image") for $user"
                fi
            done
            log "Copied $copied file(s) for $user -> $dest"
        }

        install_for_user() {
            local user="$1" home
            home="$(home_for_user "$user")"
            if [ -z "$home" ] || [ ! -d "$home" ]; then
                log "Skipping $user (no home folder)"
                return
            fi

            if [ "$INSTALL_NEW_TEAMS" -eq 1 ]; then
                copy_backgrounds "$user" "$home" "$NEW_TEAMS_UPLOADS"
            fi
            if [ "$INSTALL_CLASSIC_TEAMS" -eq 1 ]; then
                copy_backgrounds "$user" "$home" "$CLASSIC_TEAMS_UPLOADS"
            fi
        }

        console_user() {
            local user
            user="$(stat -f%Su /dev/console)"
            if [ -n "$user" ] && [ "$user" != "root" ] && [ "$user" != "loginwindow" ]; then
                echo "$user"
            fi
        }

        # Runs a command inside the logged-in user's GUI session.
        in_session() {
            if is_root; then
                launchctl asuser "$SESSION_UID" sudo -u "$SESSION_USER" "$@"
            else
                "$@"
            fi
        }

        is_running() {
            [ "$(in_session osascript -e "application id \"$1\" is running" 2>/dev/null)" = "true" ]
        }

        # Teams only picks up new uploads at launch, so quit and reopen it if it's running.
        restart_teams() {
            if is_root; then
                SESSION_USER="$(console_user)"
                if [ -z "$SESSION_USER" ]; then
                    log "No user logged in; Teams will load the backgrounds next launch."
                    return
                fi
                SESSION_UID="$(id -u "$SESSION_USER")"
            fi

            for bundle in "$NEW_TEAMS_BUNDLE_ID" "$CLASSIC_TEAMS_BUNDLE_ID"; do
                if is_running "$bundle"; then
                    log "Restarting $bundle so the new backgrounds appear"
                    in_session osascript -e "tell application id \"$bundle\" to quit" >/dev/null 2>&1
                    for _ in $(seq 1 20); do
                        is_running "$bundle" || break
                        sleep 1
                    done
                    if is_running "$bundle"; then
                        log "$bundle did not quit; the backgrounds will appear after the next restart."
                    else
                        in_session open -b "$bundle"
                    fi
                fi
            done
        }

        if is_root; then
            if [ "$ALL_USERS" -eq 1 ]; then
                USERS="$(dscl . -list /Users UniqueID | awk '$2 >= 501 { print $1 }')"
            else
                USERS="$(console_user)"
            fi
            if [ -z "$USERS" ]; then
                log "No users to install for."
            fi
            for user in $USERS; do
                install_for_user "$user"
            done
        else
            install_for_user "$(id -un)"
        fi

        if [ "$RESTART_TEAMS" -eq 1 ]; then
            restart_teams
        fi

        log "Done."
        exit 0

        """#
    }

    /// PKG postinstall: runs the installed copy of the install script, then removes the temporary payload.
    static func postinstallScript(options: BuildOptions) -> String {
        let payload = pkgPayloadPath(for: options)
        return #"""
        #!/bin/bash
        # Postinstall for \#(shellEscaped(options.packageName)): copy backgrounds into each user's Teams folder.
        PAYLOAD=\#(shellEscaped(payload))
        "$PAYLOAD/install-backgrounds.sh" "$PAYLOAD/Backgrounds" | tee -a "/var/log/TeamsBackgrounds.log"

        # The payload was only staged in /private/tmp for this step; remove it so the images
        # only exist in the Teams folders.
        rm -rf "$PAYLOAD"
        rmdir "/private/tmp/TeamsBackgrounds" 2>/dev/null
        exit 0

        """#
    }

    static func readme(options: BuildOptions, items: [BackgroundItem], scriptName: String) -> String {
        let mapping = items
            .map { "  \($0.sourceURL.lastPathComponent) -> \($0.fileName)" }
            .joined(separator: "\n")
        return """
        \(options.packageName)
        \(String(repeating: "=", count: options.packageName.count))

        To install, double-click "\(scriptName)" (or run it in Terminal).
        It copies the backgrounds into Microsoft Teams and restarts Teams if it is running.

        Target: \(options.teamsTarget.rawValue)

        New Teams folder:
          ~/Library/Containers/com.microsoft.teams2/Data/Library/Application Support/Microsoft/MSTeams/Backgrounds/Uploads
        Classic Teams folder:
          ~/Library/Application Support/Microsoft/Teams/Backgrounds/Uploads

        Images:
        \(mapping)

        """
    }

    /// Wraps a value in single quotes for safe use in a shell script.
    private static func shellEscaped(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: #"'\''"#) + "'"
    }
}
